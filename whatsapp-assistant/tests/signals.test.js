// 22.11.26: זיהוי נפילה/מצוקה, משבר וכאב בהודעות מתאמנים — ניסוחים אמיתיים מהיום. מריץ את הביטויים מ-index.js
const src = require('fs').readFileSync(require('path').join(__dirname, '..', 'index.js'), 'utf8')
const get = (n) => eval(src.match(new RegExp('const ' + n + ' = (\\/.*\\/)\\n'))[1])
const D = get('DISTRESS_RE'), C = get('CRISIS_RE'), P = get('PAIN_RE'), Q = get('Q_RE')
let fail = 0; const eq = (n, g, w) => { if (g !== w) { fail++; console.log('FAIL', n, g, w) } }
eq('עומר: כמו בהמה', D.test('מעדכן שאכלתי כמו בהמה'), true)
eq('עומר: אין לי כוח', D.test('אין לי כוח לזה כבר'), true)
eq('עומר: אמוק', D.test('כל מה שזמין הייתי באמוק'), true)
eq('עומר: בלופ', D.test('אני בלופ שנים כבר'), true)
eq('רגיל: לא מצוקה', D.test('סבבה השבוע היה 4 אימונים'), false)
eq('משבר', C.test('אני לא רוצה לחיות ככה'), true)
eq('לא משבר', C.test('אין לי כוח לזה כבר'), false)
eq('עומר: כתף', P.test('שמע איך כואב לי הכתף קדמית צד שמאל'), true)
eq('שחף: השתלה', P.test('ההשתלה עברה טוב'), true)
eq('לא כאב', P.test('אכלתי עוף ואורז'), false)
eq('שאלה עם ?', Q.test('מתי אתה יכול?'), true)
eq('שאלה בלי ?', Q.test('אפשר להחליף את הטונה בביצים'), true)
eq('לא שאלה', Q.test('סבבה אחי'), false)
console.log(fail ? `${fail} בדיקות זיהוי נכשלו` : 'בדיקות הזיהוי עברו'); process.exit(fail ? 1 : 0)
