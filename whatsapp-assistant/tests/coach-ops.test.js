// 22.11.26: פקודות מהוואטסאפ (כרטיס / תשלום / חידוש / מתאמן חדש / שינוי תפריט-תוכנית) — זיהוי וזיהוי שם, בלי רשת
const ops = require('../coach-ops')
let fail = 0; const eq = (n, g, w) => { if (JSON.stringify(g) !== JSON.stringify(w)) { fail++; console.log('FAIL', n, '\n  got ', JSON.stringify(g), '\n  want', JSON.stringify(w)) } }
ops._setClients(['שון', 'שני אהרוני', 'עידו פארחן', 'עידן קסימדזנוב', 'אודליה', 'שחף בורשטיין', 'מור דומני', 'יאן בוחבוט'].map((name) => ({ name, status: 'פעיל' })))
const M = (t) => ops.isMine(t)
eq('כרטיס', M('מה עם שני'), true); eq('כרטיס 2', M('מה המצב של עידו?'), true)
eq('תשלום', M('שחף שילם 800'), true); eq('תשלום עם פסיק', M('שון שילם 1,800'), true)
eq('חידוש x', M('אודליה חידשה 600x3'), true); eq('חידוש ×', M('אודליה חידשה 600×3'), true); eq('חידוש חודשים', M('עידן חידש ל-3 חודשים ב-600'), true)
eq('מתאמן חדש', M('מתאמן חדש: דני כהן 0501234567 600x3 חיטוב'), true)
eq('תפריט', M('תוסיף לעידו 300 קלוריות בבוקר'), true); eq('תוכנית', M('תחליף לשני סקוואט בלג-פרס בתוכנית'), true)
eq('לא: פקודת מאגר', M('תוסיף למאגר טונה 110 קלוריות 25 חלבון'), false)
eq('לא: יעד קלוריות (פקודה קיימת)', M('ליהב יעד 1400 קלוריות'), false)
eq('לא: שיחה', M('מה המצב'), false); eq('לא: טיוטה', M('1 אודליה'), false)
;(async () => {
  eq('שם: עידו לא עידן', (await ops.findName('תוסיף לעידו 300 קלוריות בבוקר') || {}).name, 'עידו פארחן')
  eq('שם: עידן', (await ops.findName('עידן חידש 600x3') || {}).name, 'עידן קסימדזנוב')
  eq('שם עם ל', (await ops.findName('תחליף לשני סקוואט') || {}).name, 'שני אהרוני')
  eq('אין שם → null', await ops.findName('מה עם הבדיקות דם'), null)
  eq('לא נתפס בתוך מילה (שמור)', await ops.findName('שמור לי את זה'), null)
  console.log(fail ? `${fail} בדיקות פקודות נכשלו` : 'בדיקות פקודות הוואטסאפ עברו'); process.exit(fail ? 1 : 0)
})()
